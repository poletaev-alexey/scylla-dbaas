"""Build a single self-contained HTML presentation from the deck sources.

    python3 docs/ai-process/deck/build.py   ->  docs/ai-process/presentation.html

The slides in slides/*.html were generated by Claude for the claude.ai Slides artifact type
(1920x1080 sections, speaker notes in <aside>). That viewer is private to the author, so this
script wraps the same slides in a tiny standalone viewer that reviewers can open from the repo:
arrow keys / click to navigate, N toggles speaker notes, the slide scales to the window.
"""

import html
import json
import re
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent / "presentation.html"

deck = json.loads((HERE / "deck.json").read_text())
fonts = "".join(f'<link rel="stylesheet" href="{f["href"]}">' for f in deck["faces"].values())

slides = []
for i, sid in enumerate(deck["order"], start=1):
    src = (HERE / "slides" / f"{sid}.html").read_text()
    m = re.search(r"<aside>(.*?)</aside>", src, re.S)
    notes = m.group(1).strip() if m else ""
    src = re.sub(r"<aside>.*?</aside>", "", src, flags=re.S)
    # Connector arrows are a custom element of the original viewer; render them as plain arrows.
    src = re.sub(r"<x-connector[^>]*></x-connector>", '<div class="arrow" aria-hidden="true"></div>', src)
    slides.append({"id": sid, "html": src, "notes": notes, "n": i})

body = "\n".join(
    f'<div class="frame" data-n="{s["n"]}">{s["html"]}'
    f'<div class="notes">{html.escape(html.unescape(s["notes"]))}</div></div>'
    for s in slides
)

page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(deck["title"])}</title>
{fonts}
<style>
  html, body {{ margin:0; height:100%; background:#0B1320; overflow:hidden; }}
  .frame {{ display:none; position:absolute; inset:0; }}
  .frame.on {{ display:block; }}
  .frame > section {{ position:absolute; left:50%; top:50%; width:1920px; height:1080px;
    box-sizing:border-box; transform-origin:center; margin:0; }}
  section p, section h2, section h3, section ul {{ margin:0; }}
  section ul {{ padding-left:1.1em; }}
  section table {{ width:100%; border-collapse:collapse; }}
  section th {{ text-align:left; font-weight:600; padding:14px 18px; border-bottom:3px solid currentColor; }}
  section td {{ padding:14px 18px; border-bottom:1px solid rgba(15,27,45,.18); vertical-align:top; }}
  .arrow {{ align-self:center; width:64px; height:3px; background:#2563C9; position:relative; flex:none; }}
  .arrow::after {{ content:""; position:absolute; right:-2px; top:-7px; border:8px solid transparent;
    border-left:12px solid #2563C9; border-right:0; }}
  .notes {{ display:none; position:fixed; left:0; right:0; bottom:0; max-height:30vh; overflow:auto;
    background:rgba(11,19,32,.94); color:#E6EDF5; font:16px/1.5 'IBM Plex Sans', Arial, sans-serif;
    padding:14px 20px; box-sizing:border-box; }}
  body.shownotes .frame.on .notes {{ display:block; }}
  .hud {{ position:fixed; right:12px; bottom:10px; color:#AFC0D3; font:13px 'JetBrains Mono', monospace;
    opacity:.75; pointer-events:none; }}
  body.shownotes .hud {{ bottom:calc(30vh + 10px); }}
</style></head>
<body>
{body}
<div class="hud" id="hud"></div>
<script>
  const frames = [...document.querySelectorAll('.frame')];
  let i = Math.max(0, Math.min(frames.length - 1, (parseInt(location.hash.slice(1)) || 1) - 1));
  function fit() {{
    const s = Math.min(innerWidth / 1920, innerHeight / 1080);
    for (const sec of document.querySelectorAll('.frame > section'))
      sec.style.transform = `translate(-50%, -50%) scale(${{s}})`;
  }}
  function show(n) {{
    i = Math.max(0, Math.min(frames.length - 1, n));
    frames.forEach((f, k) => f.classList.toggle('on', k === i));
    history.replaceState(null, '', '#' + (i + 1));
    document.getElementById('hud').textContent =
      `${{i + 1}} / ${{frames.length}}  ·  ← → navigate  ·  N notes`;
  }}
  addEventListener('keydown', e => {{
    if (['ArrowRight', 'PageDown', ' '].includes(e.key)) show(i + 1);
    else if (['ArrowLeft', 'PageUp'].includes(e.key)) show(i - 1);
    else if (e.key === 'Home') show(0);
    else if (e.key === 'End') show(frames.length - 1);
    else if (e.key.toLowerCase() === 'n') document.body.classList.toggle('shownotes');
  }});
  addEventListener('click', e => show(e.clientX > innerWidth / 3 ? i + 1 : i - 1));
  addEventListener('resize', fit);
  fit(); show(i);
</script>
</body></html>
"""
OUT.write_text(page)
print(f"wrote {OUT} ({len(slides)} slides)")
